
CREATE TABLE IF NOT EXISTS notification_audits
(
    id              UUID            NOT NULL,
    event_id        VARCHAR(64)     NOT NULL,
    from_address    VARCHAR(255),
    send_to         VARCHAR(255)    NOT NULL,
    status          VARCHAR(32)     NOT NULL,
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ,
    error_message   VARCHAR(2000),
    attempts        INT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    version         BIGINT          NOT NULL DEFAULT 0,

    CONSTRAINT pk_notification_audits
        PRIMARY KEY (id),

    CONSTRAINT uq_notification_audits_event_id
        UNIQUE (event_id),

    CONSTRAINT ck_notification_audits_status
        CHECK (
               status IN (
                          'START',
                          'VALIDATING',
                          'TEMPLATE_RENDER_START',
                          'TEMPLATE_RENDER_SUCCESS',
                          'DISPATCHING',
                          'SENT',
                          'RETRYING',
                          'FAILED',
                          'DEAD_LETTER'
                          )
               ),

    CONSTRAINT ck_notification_audits_event_id_not_blank
         CHECK (length(btrim(event_id)) > 0),
    CONSTRAINT ck_notification_audits_send_to_not_blank
         CHECK (length(btrim(send_to)) > 0),
    CONSTRAINT ck_notification_audits_finish_after_start
         CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_notification_audits_version_non_negative
         CHECK (version >= 0),
    CONSTRAINT ck_notification_audits_terminal_finished
         CHECK (status NOT IN ('SENT', 'FAILED', 'DEAD_LETTER') OR finished_at IS NOT NULL)
);

CREATE INDEX idx_notification_audit_status
    ON notification_audits (status);

CREATE INDEX idx_notification_audit_start
    ON notification_audits (started_at);

CREATE INDEX idx_notification_audit_send_to
    ON notification_audits (send_to);

CREATE INDEX idx_notification_audit_status_start
    ON notification_audits (status, started_at);

CREATE INDEX idx_notification_audit_in_flight
    ON notification_audits (started_at)
    WHERE status IN ('START', 'VALIDATING', 'TEMPLATE_RENDER_START',
                     'TEMPLATE_RENDER_SUCCESS', 'DISPATCHING', 'RETRYING');

CREATE INDEX idx_notification_audit_failures
    ON notification_audits (created_at DESC)
    WHERE status IN ('FAILED', 'DEAD_LETTER');

CREATE INDEX idx_notification_audit_created_at
    ON notification_audits (created_at);

COMMENT ON TABLE  notification_audits               IS 'Audit trail of email notification processing lifecycle';
COMMENT ON COLUMN notification_audits.id            IS 'Primary key (UUID generated by Hibernate)';
COMMENT ON COLUMN notification_audits.event_id      IS 'Unique business/event identifier, used for idempotency';
COMMENT ON COLUMN notification_audits.from_address  IS 'Sender email address';
COMMENT ON COLUMN notification_audits.send_to       IS 'Recipient email address';
COMMENT ON COLUMN notification_audits.status        IS 'Current ProcessingStatus enum value (stored as string)';
COMMENT ON COLUMN notification_audits.started_at    IS 'When processing started';
COMMENT ON COLUMN notification_audits.finished_at   IS 'When processing reached a terminal state';
COMMENT ON COLUMN notification_audits.error_message IS 'Failure details, if any';
COMMENT ON COLUMN notification_audits.created_at    IS 'Row creation time (@CreationTimestamp)';
COMMENT ON COLUMN notification_audits.updated_at    IS 'Last update time (@UpdateTimestamp)';
COMMENT ON COLUMN notification_audits.version       IS 'Optimistic locking version (@Version)';